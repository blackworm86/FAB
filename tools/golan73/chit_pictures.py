"""Golan '73 counter pictures cut from the printed Set-up Cards (docs/games/golan73/other/*SetupCard.pdf, 300 dpi scans).

Usage: python3 -I tools/golan73/chit_pictures.py
Only the pictures are raster (the photos and drawings printed on the counters); frames, numbers and lettering are drawn as
vector like every other chit. Writes web/public/golan73/chit/<name>.png, colour-corrected to the chit's own colour and with a soft edge, and web/src/golan-chit-pictures.ts with each picture's place on a 160-unit chit (as on the printed counter).
"""
import os, subprocess, tempfile, json
import numpy as np
from PIL import Image

# counter on the upright card (x, y, size px), found once by matching each counter, and the picture's box on that counter (0..256 scale)
SRC = {
    'IsraeliSetupCard': {'IC03': (388, 1121, 168), 'IC04': (557, 1117, 170), 'IC20': (1222, 1800, 170), 'IC30': (1315, 2077, 169),
                         'IC36': (1214, 2345, 170), 'M01': (1872, 735, 170)},
    'SyrianSetupCard': {'SC14': (1065, 1401, 171), 'SC15': (1735, 1403, 171), 'SC16': (1567, 1404, 169), 'SC17': (222, 1404, 167),
                        'SC46': (702, 2937, 169)},
}
PICS = {  # name: (counter, picture box on the 256-scale counter, kept clear of the lettering, the turn and the panel lines; the colour it sits on)
    'air_is': ('IC03', (16, 64, 240, 176), '#d3c598'), 'zvika': ('IC04', (46, 66, 222, 170), '#b6b188'), 'dugman': ('IC20', (46, 68, 224, 178), '#b6b188'),
    'cb_is': ('IC30', (46, 62, 222, 182), '#b6b188'), 'ew_is': ('IC36', (64, 44, 222, 194), '#b6b188'), 'skull': ('M01', (12, 62, 244, 198), '#d3c598'),
    'air_sy': ('SC14', (16, 66, 242, 186), '#dba43f'), 'cb_sy': ('SC15', (46, 60, 222, 182), '#dec046'), 'ew_sy': ('SC16', (56, 44, 222, 194), '#dec046'),
    'sam': ('SC17', (46, 60, 226, 188), '#dba43f'), 'ssm': ('SC46', (46, 62, 210, 198), '#dec046'),
}
OUT = 'web/public/golan73/chit/'; os.makedirs(OUT, exist_ok=True)
for f in os.listdir(OUT):
    if f.endswith('.jpg'): os.remove(OUT + f)                                       # the earlier whole-counter cut-outs
counters = {}
for card, boxes in SRC.items():
    with tempfile.TemporaryDirectory() as t:
        subprocess.run(['pdfimages', '-j', f'docs/games/golan73/other/{card}.pdf', f'{t}/c'], check=True)
        im = Image.open(f'{t}/c-000.jpg').convert('RGB').rotate(90, expand=True)    # the cards are scanned on their side
    for cid, (x, y, s) in boxes.items(): counters[cid] = im.crop((x, y, x + s, y + s)).resize((256, 256), Image.LANCZOS)
place = {}
for name, (cid, (x0, y0, x1, y1), under) in PICS.items():
    a = np.asarray(counters[cid].crop((x0, y0, x1, y1)).resize(((x1 - x0) * 2, (y1 - y0) * 2), Image.LANCZOS)).astype(float)
    ring = np.concatenate([a[:6].reshape(-1, 3), a[-6:].reshape(-1, 3), a[:, :6].reshape(-1, 3), a[:, -6:].reshape(-1, 3)])
    want = np.array([int(under[k:k + 2], 16) for k in (1, 3, 5)], float)
    a = np.clip(a * np.clip(want / np.median(ring, 0), 0.6, 1.4), 0, 255)          # the scan's warm cast, corrected to the chit's own colour
    h, w = a.shape[:2]; yy, xx = np.mgrid[0:h, 0:w]
    alpha = np.clip(np.minimum.reduce([xx, w - 1 - xx, yy, h - 1 - yy]) / 12, 0, 1)    # a soft edge: no seam where it meets the drawn chit
    Image.fromarray(np.dstack([a, alpha * 255]).astype(np.uint8), 'RGBA').save(f'{OUT}{name}.png', optimize=True)
    k = 160 / 256; place[name] = [round(x0 * k, 1), round(y0 * k, 1), round((x1 - x0) * k, 1), round((y1 - y0) * k, 1)]
open('web/src/golan-chit-pictures.ts', 'w').write('// generated by tools/golan73/chit_pictures.py: pictures cut from the printed counters, and their box on a 160-unit chit\n'
                                                   'export const GOLAN_PICTURES = ' + json.dumps(place) + ' as const;\n')
print(len(place), 'pictures', sum(os.path.getsize(OUT + f) for f in os.listdir(OUT)) // 1024, 'KB')
