/** The engine as the interface sees it. Every function that changes the game is wrapped so that, while `record.start()` is on, the call is written down
 *  (name and arguments, without the game; the open battle becomes a marker). In server games those calls are what is sent to the referee. */
import * as Engine from '../../engine/src';
import type { Call, Game } from '../../engine/src';
export * from '../../engine/src';

let sink: Call[] | null = null;
export const record = { start() { sink = []; }, stop(): Call[] { const s = sink ?? []; sink = null; return s; } };
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const wrap = <F extends (...a: any[]) => any>(name: string, fn: F): F => ((...a: unknown[]) => { if (sink) { const g = a[0] as Game; sink.push({ fn: name, args: a.slice(1).map((x) => (g?.battle && x === g.battle ? { $battle: 1 } : x)) }); } return fn(...a); }) as F;
