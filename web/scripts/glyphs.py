"""Outline glyphs of Roboto Condensed (Apache-2.0) as SVG path data, so chit lettering is real vector text that needs no installed font."""
import json, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
base = sys.argv[1]
chars = ''.join(chr(c) for c in range(32, 127)) + 'éèüöäßô–·×'
out = {}
for name, f in (('r', 'roboto-condensed-latin-400-normal.woff'), ('b', 'roboto-condensed-latin-700-normal.woff')):
    font = TTFont(f'{base}/{f}'); gs = font.getGlyphSet(); cmap = font.getBestCmap(); upm = font['head'].unitsPerEm; d = {}
    for ch in chars:
        g = cmap.get(ord(ch))
        if not g: continue
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:.0f}'.rstrip('0').rstrip('.') if False else str(round(v)))
        gs[g].draw(TransformPen(pen, (1000 / upm, 0, 0, -1000 / upm, 0, 0)))          # 1000 units per em, y down
        d[ch] = [round(gs[g].width * 1000 / upm), pen.getCommands()]
    out[name] = d
    out[name + 'Cap'] = round(font['OS/2'].sCapHeight * 1000 / upm)
open('src/glyphs.ts', 'w').write('// generated by scripts/glyphs.py from Roboto Condensed (Apache-2.0)\nexport const GLYPHS: Record<string, any> = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
print(len(open('src/glyphs.ts').read()) // 1024, 'KB')
